// Helper to check if event matches a section
export function eventMatchesSection(sectionValue: string, selectedSectionId: string): boolean {
  if (selectedSectionId === 'ALL') return true;
  const target = CORRIDOR_SECTIONS.find(s => s.id === selectedSectionId);
  if (!target) return true;
  const norm = (sectionValue || '').toLowerCase().replace(/[\s–—_-]+/g, '');
  return target.matchPattern.some(pattern => {
    const pNorm = pattern.toLowerCase().replace(/[\s–—_-]+/g, '');
    return norm.includes(pNorm) || pNorm.includes(norm);
  });
}

